export function t(key) {
  if (key === undefined || key === null) return ''
  const text = String(key)
  return TERM_LABELS[text] || DATA_SOURCE_LABELS[text] || FOCUS_LABELS[text] || STATUS_LABELS[text] || ERROR_LABELS[text] || VALUE_LABELS[text] || text
}

export function tStatus(value) {
  return STATUS_LABELS[String(value || 'pending')] || t(value || 'pending')
}

export function tStage(stage) {
  return STAGE_LABELS[stage] || t(stage)
}

export function tFocus(value) {
  return FOCUS_LABELS[value] || value || FOCUS_LABELS.problem_analysis
}

export function tSource(value) {
  return DATA_SOURCE_LABELS[value] || value || '未知数据来源'
}

export function tErrorType(value) {
  return ERROR_LABELS[value] || value || ERROR_LABELS.unknown_error
}
